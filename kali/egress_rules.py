#!/usr/bin/env python3
"""Print the nftables ruleset that confines the kestrel account's egress.

The wrapper confines the destinations argv names. It cannot confine a destination
a child invents for itself, and `theHarvester` does exactly that: it queries its
lookup providers from inside its own code, so no argv inspection ever sees those
hosts and no scope entry can bound them. This rule is the control for that case,
which is why the wrapper refuses the binary until the file this prints exists.

Root runs this at install time and the installer loads the output with `nft -f`,
so a ruleset the kernel rejects stops the install rather than leaving the account
unconfined behind a file that says otherwise. Only IPv4 is ever granted: the
scope is a set of IPv4 lab networks, and an IPv6 destination therefore falls
through to the drop instead of escaping the table.

Usage: egress_rules.py /etc/kestrel/scope.json "$(id -u kestrel)"
"""
import ipaddress
import socket
import sys

import kestrel_run

TABLE = "kestrel_egress"
LAB_SET = "lab"
PROVIDER_SET = "providers"
# The providers are reachable on the web ports and nowhere else: a host the
# child dials is not a licence to reach whatever address it resolves to.
PROVIDER_PORTS = "{ 80, 443 }"


def default_resolver(host):
    return [info[4][0] for info in
            socket.getaddrinfo(host, None, socket.AF_INET)]


def _addresses(host, resolver):
    if not kestrel_run.EGRESS_HOSTNAME_RE.fullmatch(host):
        raise SystemExit("egress source %r is not a bare hostname" % host)
    getter = resolver or default_resolver
    try:
        values = getter(host)
    except OSError as exc:
        raise SystemExit("egress source %s does not resolve: %s" % (host, exc))
    if not values:
        raise SystemExit("egress source %s resolved to nothing" % host)
    try:
        parsed = [ipaddress.ip_address(value) for value in values]
    except ValueError as exc:
        raise SystemExit(
            "egress source %s resolved to something that is not an address: %s"
            % (host, exc))
    # Sorted by value, not by text, so the generated file is stable and a diff
    # against a re-run shows a real change rather than a reshuffle.
    return [str(item) for item in sorted(set(parsed), key=ipaddress.ip_address)]


def _networks(scope):
    entries = scope.get("networks") or []
    if not isinstance(entries, list) or not entries:
        raise SystemExit("scope has no networks, so nothing would be reachable")
    granted = []
    for entry in entries:
        try:
            network = ipaddress.ip_network(str(entry), strict=False)
        except ValueError as exc:
            raise SystemExit("scope network %r is not a network" % entry) from exc
        if network.version != 4:
            raise SystemExit(
                "scope network %s is IPv6, which this rule cannot grant" % network)
        granted.append(str(network))
    return sorted(set(granted), key=ipaddress.ip_network)


def ruleset(scope, uid, resolver=None):
    """The ruleset text for one scope file, as the `kestrel` uid was found."""
    networks = _networks(scope)
    providers = []
    for host in scope.get("egress") or []:
        providers.extend(_addresses(str(host), resolver))
    ordered = sorted(set(providers), key=ipaddress.ip_address)

    lines = [
        "# Generated by egress_rules.py from the scope file -- edit the scope and",
        "# re-run kali/install_kestrel_run.sh; a hand edit here is overwritten.",
        "table inet %s {" % TABLE,
        "\tset %s {" % LAB_SET,
        "\t\ttype ipv4_addr",
        "\t\tflags interval",
        "\t\telements = { %s }" % ", ".join(networks),
        "\t}",
    ]
    if ordered:
        lines += [
            "",
            "\tset %s {" % PROVIDER_SET,
            "\t\ttype ipv4_addr",
            "\t\telements = { %s }" % ", ".join(ordered),
            "\t}",
        ]
    chain = [
        "",
        "\tchain egress {",
        "\t\ttype filter hook output priority filter; policy accept;",
        "",
        "\t\t# Only the service account is bounded here. The VM's own traffic and",
        "\t\t# an operator's shell are untouched.",
        "\t\tmeta skuid != %d accept" % uid,
        "",
        '\t\toifname "lo" accept',
        "\t\tct state established,related accept",
        "",
        "\t\t# Name resolution is deliberately not confined: every permitted",
        "\t\t# binary resolves targets, and a name is not a destination -- the",
        "\t\t# connection it leads to is still decided by the rules below.",
        "\t\tmeta skuid %d udp dport 53 accept" % uid,
        "\t\tmeta skuid %d tcp dport 53 accept" % uid,
        "",
        "\t\t# The lab, on any port and protocol, because that is what a scan is.",
        "\t\tmeta skuid %d ip daddr @%s accept" % (uid, LAB_SET),
    ]
    if ordered:
        chain.append("\t\tmeta skuid %d tcp dport %s ip daddr @%s accept"
                     % (uid, PROVIDER_PORTS, PROVIDER_SET))
    chain += [
        "",
        "\t\tmeta skuid %d drop" % uid,
        "\t}",
        "}",
    ]
    return "\n".join(lines + chain) + "\n"


def main(argv):
    if len(argv) != 3:
        raise SystemExit("usage: egress_rules.py SCOPE_JSON KESTREL_UID")
    try:
        uid = int(argv[2])
    except ValueError:
        raise SystemExit("the kestrel uid must be a number, not %r" % argv[2])
    # The wrapper's own reader is the authority on what a valid scope is, so the
    # firewall is never built from a file the wrapper itself would refuse.
    scope = kestrel_run.load_scope(argv[1]).as_dict()
    sys.stdout.write(ruleset(scope, uid))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
